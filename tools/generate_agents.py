#!/usr/bin/env python3
"""Materialise all 815 unit specs from the catalogue.

Every unit in ``catalogue/catalogue.json`` is handed to the engine its mechanism
family names.  The engine composes a full :class:`~adw.models.Unit` -- mission,
plan, artefacts, acceptance criteria, guardrails, human gates, config keys --
and the result is written to ``agents/`` as YAML.

Nothing here is unit-specific.  That is the point: the catalogue supplies the
data, the fourteen engines supply the behaviour, and this script only joins them.
Adding an agent means adding a workbook row and re-running the build.

    python tools/generate_agents.py            # write all 815
    python tools/generate_agents.py --check    # fail if the specs on disk are stale
    python tools/generate_agents.py --only MF14
    python tools/generate_agents.py --only A1,V1-S1
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Iterable

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install pyyaml")

from adw.guardrails import audit_unit, errors as guardrail_errors  # noqa: E402
from adw.models import Unit  # noqa: E402
from engines.base import get_engine, load_engines  # noqa: E402

CATALOGUE = REPO_ROOT / "catalogue" / "catalogue.json"
AGENTS_DIR = REPO_ROOT / "agents"

EXPECTED_TOTAL = 815

HEADER = """\
# {display}
#
# {kind} {unit_id} from the ADW MASTER AGENT CATALOGUE.
# Generated by tools/generate_agents.py from catalogue/catalogue.json.
# Behaviour lives in {family} ({module}); this file is configuration.
# Do not edit by hand -- edit the workbook or the engine and regenerate.
"""


def literal_block(dumper: yaml.SafeDumper, value: str):
    """Render multi-line strings as block scalars so missions stay readable."""
    if "\n" in value:
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", value)


class SpecDumper(yaml.SafeDumper):
    """Dumper that keeps nested lists indented, which diffs far better."""

    def increase_indent(self, flow: bool = False, indentless: bool = False):
        return super().increase_indent(flow, False)


SpecDumper.add_representer(str, literal_block)


def render(unit: Unit, family_name: str, module: str) -> str:
    header = HEADER.format(
        display=unit.display_name,
        kind="Playbook" if unit.is_playbook else "Agent",
        unit_id=unit.id,
        family=family_name,
        module=module,
    )
    body = yaml.dump(
        unit.to_dict(),
        Dumper=SpecDumper,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=98,
    )
    return header + body


def select(records: list[dict[str, Any]], only: str | None) -> list[dict[str, Any]]:
    if not only:
        return records
    wanted = {token.strip().upper() for token in only.split(",") if token.strip()}
    selected = [
        r
        for r in records
        if r["id"].upper() in wanted or r["mechanism_family"].upper() in wanted
    ]
    if not selected:
        raise SystemExit(f"--only {only!r} matched no units")
    return selected


def generate(records: Iterable[dict[str, Any]], families: dict[str, dict]) -> list[tuple[Path, str, Unit]]:
    rendered: list[tuple[Path, str, Unit]] = []
    for record in records:
        engine = get_engine(record["mechanism_family"])
        unit = engine.compose(record)
        family = families[record["mechanism_family"]]
        rendered.append(
            (
                REPO_ROOT / record["path"],
                render(unit, family["family"], family["module"]),
                unit,
            )
        )
    return rendered


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", help="comma-separated unit ids or mechanism families")
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; fail if any spec on disk differs from what would be generated",
    )
    parser.add_argument(
        "--no-audit",
        action="store_true",
        help="skip the standing-rule audit (the audit is on by default and blocks writes)",
    )
    args = parser.parse_args(argv)

    load_engines()
    catalogue = json.loads(CATALOGUE.read_text(encoding="utf-8"))
    families = {m["id"]: m for m in catalogue["mechanism_families"]}
    records = select(catalogue["units"], args.only)

    rendered = generate(records, families)

    # -- standing-rule audit before anything reaches disk -------------------
    if not args.no_audit:
        violations = [v for _, _, unit in rendered for v in audit_unit(unit)]
        blocking = guardrail_errors(violations)
        if blocking:
            print(f"standing-rule audit failed with {len(blocking)} error(s):", file=sys.stderr)
            for violation in blocking[:40]:
                print(f"  {violation}", file=sys.stderr)
            if len(blocking) > 40:
                print(f"  ... and {len(blocking) - 40} more", file=sys.stderr)
            return 1
        warned = len(violations) - len(blocking)
        if warned:
            print(f"standing-rule audit: {warned} warning(s), 0 errors")

    if args.check:
        stale = [
            str(path.relative_to(REPO_ROOT))
            for path, text, _ in rendered
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(f"{len(stale)} spec(s) are stale; re-run tools/generate_agents.py")
            for path in stale[:20]:
                print(f"  {path}")
            if len(stale) > 20:
                print(f"  ... and {len(stale) - 20} more")
            return 1
        print(f"all {len(rendered)} specs are up to date")
        return 0

    # A full run owns the directory: a unit renamed in the workbook must not
    # leave its old file behind pretending to be part of the catalogue.
    if not args.only and AGENTS_DIR.exists():
        shutil.rmtree(AGENTS_DIR)

    for path, text, _ in rendered:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    on_disk = len(list(AGENTS_DIR.rglob("*.yaml")))
    by_family = Counter(unit.mechanism_family for _, _, unit in rendered)
    by_type = Counter(unit.type.value for _, _, unit in rendered)
    by_profile = Counter(
        f"{unit.mechanism_family}:{unit.engine_profile}" for _, _, unit in rendered
    )

    print(f"wrote {len(rendered)} specs to {AGENTS_DIR.relative_to(REPO_ROOT)}/")
    print(f"files on disk: {on_disk}")
    print()
    for unit_type, count in sorted(by_type.items()):
        print(f"  {unit_type:<20} {count}")
    print()
    for family_id in sorted(by_family, key=lambda f: int(f[2:])):
        print(f"  {family_id:<6} {by_family[family_id]:>4}  {families[family_id]['family']}")
    print()
    print(f"  distinct engine profiles in use: {len(by_profile)}")

    if not args.only and on_disk != EXPECTED_TOTAL:
        print(
            f"\nERROR: {on_disk} files on disk, expected {EXPECTED_TOTAL}",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
