#!/usr/bin/env python3
"""Generate the browsable catalogue index under ``docs/``.

815 YAML files are the build artefact; they are not how a person reads the
catalogue. These pages are: one index of every unit, one page per department,
one per vertical cluster, and one per mechanism family.

    python tools/build_docs.py
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from adw.models import Unit, UnitType  # noqa: E402
from adw.registry import Catalogue, Registry  # noqa: E402

DOCS = REPO_ROOT / "docs"

GENERATED_NOTE = (
    "<!-- Generated by tools/build_docs.py from catalogue/catalogue.json. "
    "Do not edit by hand. -->\n"
)


def marks(unit: Unit) -> str:
    out = []
    if unit.is_revenue_critical:
        out.append("`*`")
    if unit.is_safety_critical:
        out.append("`◆`")
    return " ".join(out)


def link(unit: Unit, depth: int = 1) -> str:
    prefix = "../" * depth
    return f"[`{unit.id}`]({prefix}{unit.path})"


def unit_row(unit: Unit, depth: int = 1) -> str:
    name = unit.trigger if unit.is_playbook else unit.worker
    system = unit.system_agent or "—"
    return (
        f"| {link(unit, depth)} | {marks(unit)} | {name} | {system} | "
        f"`{unit.mechanism_family}` | {unit.expected_output} |"
    )


TABLE_HEAD = (
    "| ID | | Worker / trigger | System agent | Engine | Expected output (the acceptance test) |\n"
    "| --- | --- | --- | --- | --- | --- |"
)


def write(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GENERATED_NOTE + "\n".join(lines) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- #
# pages
# --------------------------------------------------------------------------- #


def build_index(catalogue: Catalogue, registry: Registry) -> None:
    totals = catalogue.totals
    lines = [
        "# Catalogue index",
        "",
        f"**{totals['units']} automation units** — "
        f"{totals['core_worker']} core workers, {totals['specialist']} vertical specialists, "
        f"{totals['playbook_universal']} universal playbooks, "
        f"{totals['playbook_vertical']} vertical playbooks.",
        "",
        "`*` revenue-critical  ·  `◆` safety-critical protocol (recognition and routing only)",
        "",
        "## Standing rules",
        "",
    ]
    for rule in catalogue.standing_rules:
        lines.append(f"- {rule}")
    lines += [
        "",
        "## Departments — the universal core",
        "",
        "| Department | Units | |",
        "| --- | ---: | --- |",
    ]
    for department in catalogue.departments.values():
        units = registry.by_department.get(department.id, [])
        lines.append(
            f"| [{department.name}](departments/{department.slug}.md) | {len(units)} | "
            f"{', '.join(u.id for u in units)} |"
        )

    lines += [
        "",
        "## Vertical clusters",
        "",
        "| # | Cluster | Archetype | Segment | Specialists | Playbooks |",
        "| --- | --- | --- | --- | ---: | ---: |",
    ]
    for vertical in catalogue.verticals.values():
        archetypes = ", ".join(a.split("-")[-1] for a in vertical.archetypes)
        lines.append(
            f"| {vertical.number} | [{vertical.name}](verticals/{vertical.slug}.md) | "
            f"{archetypes} | {vertical.segment} | {len(vertical.specialist_ids)} | "
            f"{len(vertical.playbook_ids)} |"
        )

    lines += [
        "",
        "## Mechanism families — the engines",
        "",
        "| MF | Family | Units | Status | What it does |",
        "| --- | --- | ---: | --- | --- |",
    ]
    for family in catalogue.mechanism_families.values():
        count = len(registry.by_mechanism_family.get(family.id, []))
        status = "**new**" if family.is_new else "existing"
        lines.append(
            f"| [{family.id}](engines/{family.id.lower()}.md) | {family.family} | "
            f"{count} | {status} | {family.what_it_does} |"
        )

    lines += [
        "",
        "## Universal playbooks by domain",
        "",
        "| Domain | Playbooks | |",
        "| --- | ---: | --- |",
    ]
    for domain in catalogue.domains.values():
        units = registry.by_domain.get(domain.id, [])
        lines.append(
            f"| [{domain.name}](domains/{domain.slug}.md) | {len(units)} | "
            f"{units[0].id} – {units[-1].id} |"
        )

    lines += [
        "",
        "## Archetypes",
        "",
        "| | Archetype | Recognise it by | Primary lever | Anchors |",
        "| --- | --- | --- | --- | --- |",
    ]
    for archetype in catalogue.archetypes.values():
        lines.append(
            f"| {archetype.letter} | {archetype.name} | {archetype.recognise_by} | "
            f"{archetype.primary_lever} | {', '.join(archetype.anchor_agents)} |"
        )

    write(DOCS / "CATALOGUE.md", lines)


def build_department_pages(catalogue: Catalogue, registry: Registry) -> None:
    for department in catalogue.departments.values():
        units = sorted(registry.by_department.get(department.id, []), key=lambda u: u.id)
        lines = [
            f"# {department.name}",
            "",
            f"{len(units)} core workers. Universal — every business on the platform runs this "
            "department, whatever its vertical.",
            "",
            TABLE_HEAD,
        ]
        lines += [unit_row(u, depth=2) for u in units]
        lines += ["", "[← catalogue index](../CATALOGUE.md)"]
        write(DOCS / "departments" / f"{department.slug}.md", lines)


def build_vertical_pages(catalogue: Catalogue, registry: Registry) -> None:
    for vertical in catalogue.verticals.values():
        units = sorted(registry.by_vertical.get(vertical.id, []), key=lambda u: u.id)
        specialists = [u for u in units if u.type is UnitType.SPECIALIST]
        playbooks = [u for u in units if u.type is UnitType.PLAYBOOK_VERTICAL]
        archetypes = ", ".join(
            f"{catalogue.archetypes[a].letter} — {catalogue.archetypes[a].name}"
            for a in vertical.archetypes
            if a in catalogue.archetypes
        )
        lines = [
            f"# V{vertical.number} · {vertical.name}",
            "",
            f"**Segment** {vertical.segment}  ·  **Archetype** {archetypes}",
            "",
            f"**Examples** {', '.join(vertical.examples)}",
            "",
            f"## Specialists ({len(specialists)})",
            "",
            TABLE_HEAD,
        ]
        lines += [unit_row(u, depth=2) for u in specialists]
        lines += [
            "",
            f"## Edge-case playbooks ({len(playbooks)})",
            "",
            "| ID | | Trigger | Automated handling | What stays human |",
            "| --- | --- | --- | --- | --- |",
        ]
        for unit in playbooks:
            human = "; ".join(g.decision for g in unit.human_gates)
            lines.append(
                f"| {link(unit, depth=2)} | {marks(unit)} | {unit.trigger} | "
                f"{unit.function} | {human} |"
            )
        lines += ["", "[← catalogue index](../CATALOGUE.md)"]
        write(DOCS / "verticals" / f"{vertical.slug}.md", lines)


def build_domain_pages(catalogue: Catalogue, registry: Registry) -> None:
    for domain in catalogue.domains.values():
        units = sorted(registry.by_domain.get(domain.id, []), key=lambda u: u.id)
        lines = [
            f"# {domain.name} — universal playbooks",
            "",
            f"{len(units)} playbooks. Universal: these edge cases occur in every vertical.",
            "",
            "| ID | | Trigger | Automated handling | Expected output | What stays human |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for unit in units:
            human = "; ".join(g.decision for g in unit.human_gates)
            lines.append(
                f"| {link(unit, depth=2)} | {marks(unit)} | {unit.trigger} | {unit.function} | "
                f"{unit.expected_output} | {human} |"
            )
        lines += ["", "[← catalogue index](../CATALOGUE.md)"]
        write(DOCS / "domains" / f"{domain.slug}.md", lines)


def build_engine_pages(catalogue: Catalogue, registry: Registry) -> None:
    for family in catalogue.mechanism_families.values():
        units = sorted(registry.by_mechanism_family.get(family.id, []), key=lambda u: u.id)
        profiles = Counter(u.engine_profile for u in units)
        lines = [
            f"# {family.id} · {family.family}",
            "",
            f"{family.what_it_does}",
            "",
            f"**Status** {family.status}  ·  **Units carried** {len(units)}  ·  "
            f"**Module** `{family.module}`",
            "",
            f"## Profiles ({len(profiles)})",
            "",
            "One engine covers many differently-named workers by having a profile per real "
            "shape in the data. A profile is pure configuration.",
            "",
            "| Profile | Units |",
            "| --- | ---: |",
        ]
        for name, count in profiles.most_common():
            lines.append(f"| `{name}` | {count} |")
        lines += ["", f"## Units ({len(units)})", "", TABLE_HEAD]
        lines += [unit_row(u, depth=2) for u in units]
        lines += ["", "[← catalogue index](../CATALOGUE.md)"]
        write(DOCS / "engines" / f"{family.id.lower()}.md", lines)


def main() -> int:
    catalogue = Catalogue.load()
    registry = Registry.load()

    build_index(catalogue, registry)
    build_department_pages(catalogue, registry)
    build_vertical_pages(catalogue, registry)
    build_domain_pages(catalogue, registry)
    build_engine_pages(catalogue, registry)

    pages = len(list(DOCS.rglob("*.md")))
    print(f"wrote {pages} documentation pages to {DOCS.relative_to(REPO_ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
